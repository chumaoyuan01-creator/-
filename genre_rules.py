def build_genre_rules_text(genre, format_type='article'):
    rules = get_genre_rules(genre)
    if not rules:
        return ''
    fmt = get_format_rules(format_type)
    lines = []
    lines.append('【体裁定位】')
    lines.append('本篇要写成：' + fmt['name'] + '。' + fmt['definition'])
    lines.append('')
    lines.append('【体裁结构要求（最重要）】')
    lines.append('1. ' + fmt['structure_rule'])
    lines.append('2. ' + fmt['main_line'])
    lines.append('3. ' + fmt['section_title_rule'])
    lines.append('4. 语言侧重：' + fmt['language_focus'])
    lines.append('5. 结尾：' + fmt['ending_rule'])
    lines.append('6. 严禁：' + fmt['forbidden_format'])
    lines.append('')
    lines.append('【标题要求】')
    lines.append(rules.get('title_formula', ''))
    lines.append('')
    lines.append('【开头要求】')
    lines.append(rules.get('opening', ''))
    lines.append('')
    lines.append('【题材写作要点】')
    lines.append(rules.get('structure', ''))
    lines.append('')
    tech = MASTER_TECHNIQUES.get(genre, '')
    if tech:
        lines.append('【名家笔法参考】')
        lines.append(tech)
        lines.append('')
    lines.append('【分析深度】')
    lines.append(rules.get('depth', ''))
    lines.append('')
    lines.append('【语言风格】')
    lines.append(rules.get('language', ''))
    lines.append('')
    lines.append('【金句要求】')
    lines.append(rules.get('golden_sentence', ''))
    lines.append('')
    lines.append('【素材使用】')
    lines.append(rules.get('source_usage', ''))
    lines.append('')
    forbidden = rules.get('forbidden', [])
    if forbidden:
        lines.append('【禁用内容】')
        lines.append('禁止使用以下词汇和写法：' + '、'.join(forbidden))
        lines.append('')
    anti_ai = rules.get('anti_ai', '')
    if anti_ai:
        lines.append('【去AI痕迹】')
        lines.append(anti_ai)
        lines.append('')
    word_count = rules.get('word_count', '')
    if word_count:
        lines.append('【篇幅要求】')
        lines.append(word_count)
        lines.append('')
    extra = rules.get('extra', '')
    if extra:
        lines.append('【附加要求】')
        lines.append(extra)
    return '\n'.join(lines)
