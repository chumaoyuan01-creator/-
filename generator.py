# 修饰词库 - 用于模板变体生成
# ============================================================

MODIFIERS = {
    'time': ['那天', '某个午后', '夜深时', '清晨', '黄昏时分', '午后', '傍晚', '深夜', '那个冬天', '那年夏天'],
    'mood': ['静静地', '默默地', '忽然', '不知为何', '不知什么时候', '不知不觉得', '下意识地', '不由自主地'],
    'scene': ['远处', '身旁', '眼前', '脚下', '身后', '四周', '不远处', '更远处'],
}

# ============================================================
# 章节标题模板
# ============================================================

CHAPTER_TITLE_TEMPLATES = [
    '第{index}章 {title}',
    '第{index}章 · {title}',
    '{index}. {title}',
]

# ============================================================
# 工具函数
# ============================================================

def _pick_unique(pool, used_set, **kwargs):
    """从模板池中选取未使用过的模板"""
    available = [t for t in pool if t not in used_set]
    if not available:
        available = pool
    template = random.choice(available)
    used_set.add(template)
    return template.format(**kwargs)


def _add_modifier(text):
    """给段落添加修饰词，生成变体"""
    # 随机选择一种修饰方式
    mod_type = random.choice(list(MODIFIERS.keys()))
    mod_word = random.choice(MODIFIERS[mod_type])
    
    # 在段落开头添加修饰词
    if random.random() < 0.5:
        if not text.startswith(mod_word):
            return mod_word + '，' + text
    # 在段落中间某处插入场景描写
    else:
        sentences = text.split('。')
        if len(sentences) > 2:
            insert_pos = random.randint(1, len(sentences) - 2)
            scene_word = random.choice(MODIFIERS['scene'])
            sentences.insert(insert_pos, scene_word + '的一切似乎都静止了')
            return '。'.join(sentences)
    return text


def _generate_variant_paragraph(template_text, used_set, **kwargs):
    """生成段落变体：先用模板填充，再添加修饰"""
    base = _pick_unique(template_text, used_set, **kwargs)
    # 50% 概率添加修饰
    if random.random() < 0.5:
        return _add_modifier(base)
    return base


# ============================================================
# 短文生成
# ============================================================

def generate_article(genre, topic, keyword, length='medium'):
    """生成短文章"""
    if genre not in TEMPLATES:
        genre = '散文'

    template = TEMPLATES[genre]
    used = set()

    body_count = {'short': 1, 'medium': 2, 'long': 3}.get(length, 2)

    intro = _pick_unique(template['intros'], used, topic=topic)
    bodies = [_generate_variant_paragraph(template['bodies'], used, keyword=keyword) for _ in range(body_count)]
    outro = _pick_unique(template['outros'], used, topic=topic)

    paragraphs = [intro] + bodies + [outro]
    return '\n\n'.join(paragraphs)


# ============================================================
# 长文生成（支持几万字）
# ============================================================

def generate_long_article(genre, topic, keyword, target_words=10000):
    """生成长文，分章节返回"""
    if genre not in TEMPLATES:
        genre = '散文'

    template = TEMPLATES[genre]

    # 根据目标字数计算章节数和每章段落数
    words_per_chapter = 1000
    total_chapters = max(3, target_words // words_per_chapter)
    # 限制每章段落数，避免过度消耗模板池
    paragraphs_per_chapter = max(4, min(8, words_per_chapter // 150))

    # 全局已使用模板集合
    global_used = set()

    # 打乱章节标题顺序
    chapter_titles = list(template['chapter_titles'])
    random.shuffle(chapter_titles)

    chapters = []

    for idx in range(1, total_chapters + 1):
        # 章节标题
        if idx - 1 < len(chapter_titles):
            raw_title = chapter_titles[idx - 1].format(topic=topic, keyword=keyword)
        else:
            raw_title = _pick_unique(template['chapter_titles'], global_used, topic=topic, keyword=keyword)

        title_template = random.choice(CHAPTER_TITLE_TEMPLATES)
        chapter_title = title_template.format(index=idx, title=raw_title)

        paragraphs = []

        if idx == 1:
            intro = _pick_unique(template['intros'], global_used, topic=topic)
            paragraphs.append(intro)
        else:
            transition = _pick_unique(template['transitions'], global_used, topic=topic, keyword=keyword)
            paragraphs.append(transition)

        # 章节正文 - 使用变体生成
        for i in range(paragraphs_per_chapter):
            body = _generate_variant_paragraph(template['bodies'], global_used, keyword=keyword)
            paragraphs.append(body)

            if i < paragraphs_per_chapter - 1 and random.random() < 0.25:
                t = _pick_unique(template['transitions'], global_used, topic=topic, keyword=keyword)
                paragraphs.append(t)

        if idx == total_chapters:
            outro = _pick_unique(template['outros'], global_used, topic=topic)
            paragraphs.append(outro)

        content = '\n\n'.join(paragraphs)
        word_count = len(content.replace('\n', '').replace(' ', ''))

        chapters.append({
            'chapter_index': idx,
            'chapter_title': chapter_title,
            'content': content,
            'word_count': word_count,
        })

    return chapters


